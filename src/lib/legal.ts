// para usuarios que aceptaron una versión anterior.
//
// 1.7 (03/09/2026) — Productos Digitales, y un arreglo que sale de él.
//   · Faltaba la solapa "Productos Digitales" en los dos documentos, y el
//     problema no era que faltara: era que le dábamos OTRO. El registro armaba
//     el link con una cadena de tres condiciones —seller, owner, y todo lo demás
//     a "buyer"— escrita cuando los tipos de cuenta eran tres. Al aparecer el
//     cuarto, quien se registraba en Productos Digitales aceptaba los términos
//     del Cliente: el documento de alguien que COMPRA en una tienda, y el que
//     promete 10 días de arrepentimiento para todo. Ahora el rol viaja entero.
//   · Los archivos de descarga inmediata están exceptuados del derecho de
//     arrepentimiento por el art. 1116 inc. b del Código Civil y Comercial. Se
//     escribe en el punto 6 ter del Cliente y se nombra la excepción en el
//     punto 7 de sus derechos, con las dos condiciones que la sostienen: si no
//     lo descargó el derecho corre completo, y la garantía que ofrezca quien
//     vende le gana a la excepción ("excepto pacto en contrario").
//   · La privacidad no declaraba dos datos personales que el sistema empezó a
//     guardar: la dirección IP de quien acepta esa condición antes de pagar, y
//     la IP y el navegador de cada descarga. Estaban en los términos y faltaban
//     ahí. Se declaran en las dos solapas —la de quien vende y la de quien
//     compra— con su finalidad, su base legal y su plazo.
//   · El aviso de TRANSFERENCIA INTERNACIONAL estaba escrito en una sola solapa
//     —la de Dueño de tienda— y es un hecho de la plataforma entera: la base
//     corre en aws-1-us-east-2 y el hosting también. O sea que los datos de quien
//     vende afiliado, de quien compra, de quien dona y de quien vende productos
//     digitales salían del país exactamente igual, y ninguno de los cuatro lo
//     estaba leyendo. Lo exige el art. 12 de la Ley 25.326. Ahora está en las
//     cinco, desde una sola constante para que no se puedan desincronizar.
//     Salió de comparar nuestro temario contra el de un competidor —ellos sí
//     tenían su propia sección— y de mirar a dónde apunta de verdad la base.
//   · Se nombra el DOBLE ROL en la solapa de Productos Digitales: sobre los
//     datos de su cuenta el responsable es TiendaApps; sobre los de sus
//     compradores el responsable es quien vende, y nosotros somos el encargado.
//     No es una formalidad: define a quién le llega un pedido de acceso o de
//     borrado de un comprador. Antes estaba dicho como una obligación suelta
//     ("respondés vos por ese uso") y no como lo que es.
//   · Cinco secciones más en los términos de Productos Digitales, salidas de
//     comparar el temario contra el de un competidor (mismo día, sin publicar
//     la 1.7 en el medio — por eso no hay 1.8):
//       - "2 bis. Qué somos en tu venta": no había UNA LÍNEA sobre el rol de la
//         plataforma. El art. 40 de la Ley 24.240 hace solidariamente
//         responsable a toda la cadena de comercialización, y una plataforma que
//         aloja el archivo, cobra reteniendo su comisión y manda el mail de
//         entrega desde su propio dominio está más adentro de esa cadena que un
//         software que sólo presta pantallas. La sección encuadra la relación y
//         dice en voz alta que NO recorta derechos: el art. 40 es de orden
//         público y ninguna cláusula lo apaga.
//       - "3 bis. Los impuestos son tuyos": la palabra "impuestos" aparecía una
//         sola vez en todo el documento, y era en el derecho del comprador a
//         saber el precio final. Cero sobre el vendedor.
//       - "4 bis. Tu contenido sigue siendo tuyo": faltaba el PERMISO. Los
//         términos del Dueño de tienda tienen su licencia desde siempre; estos
//         no, así que guardábamos el PDF de alguien, lo firmábamos y se lo
//         mandábamos por mail a terceros sin una línea que dijera que nos
//         autorizó.
//       - "4 ter. Funciones con IA": los planes ya las venden, así que el
//         reparto de responsabilidades tiene que estar antes de que la primera
//         se encienda.
//       - "8 bis. Suspensión y baja": la facultad de cortar estaba dicha de
//         refilón y sin criterio. Incluye lo que importa de verdad: una baja no
//         toca los permisos de descarga ya vendidos, porque quien compró no
//         tiene nada que ver con el motivo de la baja.
//     Quedan a decisión del titular, no escritas: limitación de responsabilidad,
//     ley aplicable y jurisdicción, y la cláusula de no garantía de resultados.
//
// 1.8 (04/09/2026) — tres cosas de Productos Digitales que el producto ya hacía
//     y el documento no decía. Las tres nacen de la misma fase: cada producto
//     pasó a tener su propia dirección y, en Pro, su propio dominio.
//   · "2 ter. La dirección de tu producto, y tu dominio": NO EXISTÍA NADA. La
//     sección 4 del Dueño habla de dominio propio, pero es de otro apartado y de
//     otro producto —allá es uno por cuenta y acá uno por producto—, así que una
//     cuenta digital que conectaba su dominio no tenía una línea que dijera de
//     quién es, quién lo paga ni qué pasa si lo desconecta. Y falta lo más
//     delicado: la dirección de tiendaapps es NUESTRA y se presta. Quien va a
//     pautar contra ella durante meses tiene que saberlo antes de gastar el
//     primer peso en publicidad, y saber que cambiarla rompe lo repartido.
//   · "4 quater. El ebook escrito con IA": el 4 ter habla de la IA que escribe
//     los textos de la página. Esto es otra cosa —un archivo escrito por una
//     máquina que después se VENDE a un tercero por plata—, y lo que allá es un
//     borrador que se revisa antes de publicar, acá es la mercadería. Dice que
//     puede tener datos inventados, que no es asesoramiento profesional, que
//     leerlo entero antes de venderlo es del vendedor, y que el resultado es
//     suyo pero no se le garantiza que sea único.
//   · Los bonos y los upsells en la sección 5: no aparecían en ninguna parte del
//     documento aunque se entregan en cada compra. Un bono es un archivo que
//     alguien recibe por haber pagado, aunque su precio sea cero: le corren las
//     mismas reglas de entrega, devolución y responsabilidad que al principal.
//     Sin esto, el archivo que más se regala era el único sin reglas escritas.
//   · Y la POLÍTICA DE PRIVACIDAD, "3 bis. Compras que alguien empezó y no
//     terminó" (05/09). La solapa digital no tenía una sola mención a la palabra
//     "carrito" y la función que le escribe a esa gente ya estaba escrita:
//     alguien deja la compra por la mitad, el vendedor le ve el correo en su
//     panel y —en Pro— nosotros le mandamos un mail en su nombre. Nada de eso
//     estaba declarado. Se escribe qué se guarda, con qué base legal (interés
//     legítimo, art. 5 inc. f de la 25.326), que el recordatorio sale UNA sola
//     vez y que nunca se le escribe a quien tiene el pago en camino.
//     Y se promete que esa compra sin pagar se borra a los 45 días, lo que
//     obligó a escribir la limpieza que lo cumple: hasta ahora quedaban PARA
//     SIEMPRE con el correo de alguien que ni siquiera llegó a comprar.
//     El mismo párrafo se agrega a la solapa de Cliente, que hablaba sólo de
//     carritos de tienda —con cupón y WhatsApp—, cosas que acá no existen.
//   ⚠️ Siguen sin escribirse, y siguen siendo decisión del titular: limitación de
//     responsabilidad, ley aplicable y jurisdicción, y la cláusula de no garantía
//     de resultados. Y este texto todavía no lo leyó un abogado de consumo.
//
// 1.9 (14/09/2026) — dos reglas de Productos Digitales que cambiaron ese día,
//     y una de las dos CONTRADECÍA lo escrito.
//   · "2 ter", el dominio propio sin Pro. Decía "si tu plan Pro se vence, el
//     dominio que ya tenías conectado sigue funcionando", y desde hoy no: sin
//     Pro el dominio REDIRIGE a la dirección de tiendaapps —no se rompe ni se
//     pierde—, vuelve solo si vuelve Pro, y a los 90 días sin Pro lo
//     desconectamos de nuestro lado con aviso 7 días antes. Los números salen
//     de la misma constante que los aplica (`DIAS_DE_DOMINIO_EN_FREE`). Sin
//     esto, un vendedor que cae a Free tenía un documento que le prometía lo
//     contrario de lo que le pasaba.
//   · Sección 5, el reemplazo del archivo. El enlace de descarga entrega el
//     archivo que el producto tiene EN ESE MOMENTO, no una copia congelada de
//     la compra (es lo que hacen Hotmart y Gumroad, y sirve para corregir).
//     El documento no lo decía. Ahora dice que quien compró baja la versión
//     nueva mientras le dure el enlace, y que pisar un producto con otro
//     distinto es responsabilidad del vendedor frente a quien compró.
//   ⚠️ Siguen a decisión del titular: limitación de responsabilidad, ley
//     aplicable y jurisdicción, no garantía de resultados. Sin abogado todavía.
//
// 1.6 (11/08/2026) — tres arreglos que salieron de revisar el texto, no de un
// cambio de producto:
//   · La sección 5 del Dueño decía "sos responsable de las comisiones que
//     acordés con tus afiliados" y la 6, en el mismo documento, "TiendaApps es
//     el responsable directo del pago de comisiones". Un afiliado que no cobraba
//     podía reclamarle al dueño con la 5 en la mano y el dueño mandarlo acá con
//     la 6. Gana la 6, que es la que describe cómo funciona de verdad: la 5
//     ahora habla solo de definir el porcentaje y avisar los cambios.
//   · El borrado definitivo de cuenta no estaba documentado en los términos del
//     Dueño. La sección 7 lo remitía a "la sección 8", que es Propiedad
//     intelectual — el número venía copiado de los términos del Cliente, donde
//     la 8 sí es cancelación de cuenta. Se agrega 7 quater con lo que el sistema
//     hace de verdad (anonimizar los registros fiscales en vez de borrarlos,
//     liberar el email, los bloqueos por pedidos y comisiones pendientes).
//   · Faltaba la solapa "Donante", que sí existe en la Política de Privacidad.
//     /comunidad manda a ?role=donor y quien venía de ahí caía en "Cliente" sin
//     aviso, aunque donar no requiere cuenta ni haber comprado nada.
//
// 1.5 (07/08/2026) — topes de productos. El plan Pro pasa a tener uno (1.000
// publicados), y aparece además un techo de 5.000 por tienda que corre para
// cualquier plan, Premium incluido. Ese segundo no es comercial: las tres rutas
// que crean productos (alta, importación de CSV y duplicar) no tenían ni tope de
// cantidad ni límite de ritmo, y como el plan se elige solo al registrarse y la
// prueba no pide tarjeta, un tope que mirara únicamente el plan no frenaba a
// quien lo quisiera evadir. Se documenta porque el usuario se lo puede chocar.
//
// 1.4 (20/07/2026) — promociones de tienda: tope del plan Pro (5 vigentes, más el
// de 10 cupones ahora bien definido), su borrado y respaldo en el cambio de rubro,
// y el bloqueo del cambio cuando hay ofertas que un cliente todavía puede usar.
